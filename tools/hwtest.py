#!/usr/bin/env python3
"""Hardware test harness for ESC/POS thermal printers.

Every action is appended (timestamp, bytes sent, bytes received, notes) to
docs/hardware/<label>/log.md so the reverse-engineering log writes itself.

Setup (once):
    python3 -m venv tools/.venv && tools/.venv/bin/pip install pyusb pyserial pillow bleak
    sudo cp linux/99-thermal-printer.rules /etc/udev/rules.d/ && sudo udevadm control --reload && sudo udevadm trigger

Typical session:
    tools/.venv/bin/python tools/hwtest.py detect
    tools/.venv/bin/python tools/hwtest.py --label hz8360 dump
    tools/.venv/bin/python tools/hwtest.py --label hz8360 status
    tools/.venv/bin/python tools/hwtest.py --label hz8360 --width 576 print text ruler gradient bands density cut
    tools/.venv/bin/python tools/hwtest.py --label mp583 --width 384 print photo --image some.jpg

Transports:  --usb VID:PID (default: auto-detect, via libusb, detaches usblp)
             --dev /dev/usb/lp0 | /dev/ttyACM0 | /dev/rfcomm0
             --ble AA:BB:CC:DD:EE:FF   (bleak; see ble-scan / ble-dump)
"""
