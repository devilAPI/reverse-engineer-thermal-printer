# --------------------------------------------------------------------------- log
class Log:
    def __init__(self, label):
        self.dir = ROOT / "docs" / "hardware" / label
        self.dir.mkdir(parents=True, exist_ok=True)
        self.path = self.dir / "log.md"
        if not self.path.exists():
            self.path.write_text(f"# Hardware log: {label}\n\nAuto-generated by `tools/hwtest.py`.\n")

    def section(self, title):
        stamp = dt.datetime.now().strftime("%Y-%m-%d %H:%M:%S")
        self._w(f"\n## {stamp} — {title}\n")
        print(f"\n== {title}")

    def note(self, text):
        self._w(text + "\n")
        print(text)

    def block(self, text, lang=""):
        self._w(f"```{lang}\n{text.rstrip()}\n```\n")
        print(text)

    def tx(self, name, data):
        self.note(f"- TX `{name}`: {len(data)} B `{hexs(data, 48)}`")

    def rx(self, name, data):
        if data:
            printable = "".join(chr(b) if 32 <= b < 127 else "." for b in data)
            self.note(f"- RX `{name}`: {len(data)} B `{hexs(data, 64)}` |{printable[:64]}| bits={bits(data[:4])}")
        else:
            self.note(f"- RX `{name}`: (no reply)")

    def _w(self, s):
        with self.path.open("a") as f:
            f.write(s)


def hexs(b, limit):
    h = b[:limit].hex(" ")
    return h + (" …" if len(b) > limit else "")


def bits(b):
    return " ".join(f"{x:08b}" for x in b)


# --------------------------------------------------------------------- transports
class UsbLink:
    def __init__(self, vidpid=None):
        import usb.core
        import usb.util
        self.usb = usb
        dev = None
        if vidpid:
            v, p = (int(x, 16) for x in vidpid.split(":"))
            dev = usb.core.find(idVendor=v, idProduct=p)
        else:
            cands = [d for d in usb.core.find(find_all=True) if is_candidate(d)]
            if len(cands) > 1:
                raise SystemExit("Several candidates, pass --usb VID:PID:\n" + "\n".join(describe(d) for d in cands))
            dev = cands[0] if cands else None
        if dev is None:
            raise SystemExit("No printer found (see `detect`)")
        self.dev = dev
        self.reattach = []
        cfg = dev.get_active_configuration()
        self.intf = self.ep_out = self.ep_in = None
        for intf in cfg:
            outs = [e for e in intf if usb.util.endpoint_direction(e.bEndpointAddress) == usb.util.ENDPOINT_OUT
                    and usb.util.endpoint_type(e.bmAttributes) == usb.util.ENDPOINT_TYPE_BULK]
            if outs:
                ins = [e for e in intf if usb.util.endpoint_direction(e.bEndpointAddress) == usb.util.ENDPOINT_IN
                       and usb.util.endpoint_type(e.bmAttributes) == usb.util.ENDPOINT_TYPE_BULK]
                self.intf, self.ep_out, self.ep_in = intf, outs[0], (ins[0] if ins else None)
                break
        if self.intf is None:
            raise SystemExit("No bulk OUT endpoint")
        n = self.intf.bInterfaceNumber
        try:
            if dev.is_kernel_driver_active(n):
                dev.detach_kernel_driver(n)
                self.reattach.append(n)
        except (NotImplementedError, usb.core.USBError):
            pass
        usb.util.claim_interface(dev, n)
        self.name = f"usb {dev.idVendor:04x}:{dev.idProduct:04x} if{n} out=0x{self.ep_out.bEndpointAddress:02x}" + (
            f" in=0x{self.ep_in.bEndpointAddress:02x}" if self.ep_in else " (no IN)")

    def write(self, data, chunk=4096, delay=0.0):
        for i in range(0, len(data), chunk):
            self.ep_out.write(data[i:i + chunk], timeout=10000)
            if delay:
                time.sleep(delay)

    def read(self, timeout=0.5):
        if not self.ep_in:
            return b""
        out = b""
        deadline = time.time() + timeout
        while time.time() < deadline:
            try:
                out += bytes(self.ep_in.read(self.ep_in.wMaxPacketSize, timeout=int(timeout * 1000)))
            except self.usb.core.USBTimeoutError:
                break
            except self.usb.core.USBError:
                break
        return out

    def close(self):
        self.usb.util.release_interface(self.dev, self.intf.bInterfaceNumber)
        for n in self.reattach:
            try:
                self.dev.attach_kernel_driver(n)
            except Exception:  # noqa: BLE001
                pass


class DevLink:
    def __init__(self, path):
        self.name = f"dev {path}"
        self.fd = os.open(path, os.O_RDWR | os.O_NOCTTY | os.O_NONBLOCK)
        if "tty" in path or "rfcomm" in path:
            import termios
            import tty
            tty.setraw(self.fd)
            attrs = termios.tcgetattr(self.fd)
            attrs[4] = attrs[5] = termios.B115200
            termios.tcsetattr(self.fd, termios.TCSANOW, attrs)

    def write(self, data, chunk=4096, delay=0.0):
        for i in range(0, len(data), chunk):
            view = memoryview(data)[i:i + chunk]
            while view:
                try:
                    n = os.write(self.fd, view)
                    view = view[n:]
                except BlockingIOError:
                    time.sleep(0.005)
            if delay:
                time.sleep(delay)

    def read(self, timeout=0.5):
        out = b""
        deadline = time.time() + timeout
        while time.time() < deadline:
            try:
                out += os.read(self.fd, 256)
            except (BlockingIOError, OSError):
                time.sleep(0.02)
        return out

    def close(self):
        os.close(self.fd)


class BleLink:
    """Synchronous wrapper around bleak for the harness."""

    def __init__(self, addr, rate=4500):
        from bleak import BleakClient
        self.loop = asyncio.new_event_loop()
        self.client = BleakClient(addr)
        self.rx = bytearray()
        self.rate = rate
        self.loop.run_until_complete(self.client.connect(timeout=20))
        chars = {c.uuid.lower(): c for s in self.client.services for c in s.characteristics}
        self.char = next((chars[u] for u in BLE_WRITE_CHARS if u in chars), None)
        if self.char is None:
            self.char = next(c for c in chars.values() if "write-without-response" in c.properties)
        self.noresp = "write-without-response" in self.char.properties
        for c in chars.values():
            if "notify" in c.properties:
                try:
                    self.loop.run_until_complete(self.client.start_notify(c, lambda _h, d: self.rx.extend(d)))
                except Exception:  # noqa: BLE001
                    pass
        mtu = getattr(self.client, "mtu_size", 23)
        self.payload = max(20, min(mtu - 3, 180))
        self.name = f"ble {addr} char={self.char.uuid} mtu={mtu} noresp={self.noresp}"

    def write(self, data, chunk=None, delay=0.0):
        step = self.payload
        per = step / self.rate
        for i in range(0, len(data), step):
            t = time.time()
            self.loop.run_until_complete(
                self.client.write_gatt_char(self.char, data[i:i + step], response=not self.noresp))
            left = per - (time.time() - t)
            if left > 0:
                time.sleep(left)

    def read(self, timeout=0.5):
        self.loop.run_until_complete(asyncio.sleep(timeout))
        out, self.rx = bytes(self.rx), bytearray()
        return out

    def close(self):
        time.sleep(0.5)
        self.loop.run_until_complete(self.client.disconnect())


# ------------------------------------------------------------------------ helpers
def is_candidate(d):
    if (d.idVendor, d.idProduct) in KNOWN_IDS:
        return True
    try:
        for intf in d.get_active_configuration():
            if intf.bInterfaceClass in (0x07,):
                return True
    except Exception:  # noqa: BLE001
        pass
    return False


def describe(d):
    import usb.util
    def s(i):
        try:
            return usb.util.get_string(d, i) if i else ""
        except Exception:  # noqa: BLE001
            return "?"
    classes = []
    try:
        for intf in d.get_active_configuration():
            classes.append(f"if{intf.bInterfaceNumber}:{intf.bInterfaceClass:02x}/{intf.bInterfaceSubClass:02x}/{intf.bInterfaceProtocol:02x}")
    except Exception as e:  # noqa: BLE001
        classes.append(f"(config unreadable: {e})")
    mark = "*" if (d.idVendor, d.idProduct) in KNOWN_IDS else " "
    return (f"{mark} {d.idVendor:04x}:{d.idProduct:04x} bus{d.bus}.{d.address} "
            f"'{s(d.iManufacturer)}' '{s(d.iProduct)}' sn='{s(d.iSerialNumber)}' {' '.join(classes)}")


def font(size):
    for p in ["/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf",
              "/usr/share/fonts/truetype/liberation/LiberationSans-Bold.ttf"]:
        if os.path.exists(p):
            return ImageFont.truetype(p, size)
    return ImageFont.load_default()


def img_job(img, band=255, mode=0):
    bw = img if img.mode == "1" else img.convert("1")
    data = raster_bytes(bw, band)
    if mode:
        data = data.replace(bytes([GS, 0x76, 0x30, 0]), bytes([GS, 0x76, 0x30, mode]))
    return data


def text(s):
    return s.encode("cp437", "replace") + b"\n"


# -------------------------------------------------------------------- test pages
def page_text(w):
    return (bytes([ESC, 0x40]) + text("hwtest: text") +
            bytes([ESC, 0x21, 0x00]) + text("Font A 0123456789 ABCDEFGHIJKLMNOPQRSTUVWXYZ") +
            bytes([ESC, 0x21, 0x01]) + text("Font B 0123456789 ABCDEFGHIJKLMNOPQRSTUVWXYZ") +
            bytes([ESC, 0x21, 0x30]) + text("BIG") + bytes([ESC, 0x21, 0x00]) +
            bytes([ESC, 0x45, 1]) + text("bold") + bytes([ESC, 0x45, 0]) +
            bytes([ESC, 0x61, 1]) + text("centered") + bytes([ESC, 0x61, 0]) +
            bytes([ESC, 0x64, 2]))


def page_ruler(w):
    """Ticks every 8 dots, labels every 64, over a width wider than the paper,
    to find the real printable width and left offset."""
    test_w = 640 if w > 384 else 448
    im = Image.new("1", (test_w, 90), 1)
    d = ImageDraw.Draw(im)
    for x in range(0, test_w, 8):
        h = 40 if x % 64 == 0 else (25 if x % 32 == 0 else 12)
        d.line([(x, 0), (x, h)], fill=0)
    for x in range(0, test_w, 64):
        d.text((x + 2, 45), str(x), fill=0, font=font(14))
    d.line([(0, 88), (test_w - 1, 88)], fill=0)
    d.rectangle([(0, 0), (w - 1, 89)], outline=0)
    return bytes([ESC, 0x40]) + text(f"ruler: box = {w} dots, ticks/8") + img_job(im) + bytes([ESC, 0x64, 2])


def gradient_image(w, h=60):
    im = Image.new("L", (w, h))
    px = im.load()
    for y in range(h):
        for x in range(w):
            px[x, y] = int(255 * x / (w - 1))
    return im


def page_gradient(w):
    out = bytearray([ESC, 0x40])
    g = gradient_image(w)
    out += text("gradient: Floyd-Steinberg")
    out += img_job(g.convert("1", dither=Image.FLOYDSTEINBERG))
    out += text("gradient: threshold")
    out += img_job(g.convert("1", dither=Image.NONE))
    out += text("gradient: 16 steps")
    steps = Image.new("L", (w, 40))
    d = ImageDraw.Draw(steps)
    for i in range(16):
        d.rectangle([(i * w // 16, 0), ((i + 1) * w // 16, 39)], fill=i * 17)
    out += img_job(steps.convert("1", dither=Image.FLOYDSTEINBERG))
    out += bytes([ESC, 0x64, 2])
    return bytes(out)


def page_bands(w):
    """Same pattern with different GS v 0 band heights — look for gaps,
    garbage or truncation to find the buffer limit."""
    out = bytearray([ESC, 0x40])
    for band in (24, 64, 128, 255, 512, 1024):
        im = Image.new("1", (w, 300), 1)
        d = ImageDraw.Draw(im)
        for y in range(0, 300, 10):
            d.line([(0, y), (w - 1, y + 10)], fill=0)
        d.rectangle([(0, 0), (w - 1, 299)], outline=0)
        out += text(f"band={band} ({w // 8 * band} B/cmd)")
        out += img_job(im, band)
    out += bytes([ESC, 0x64, 2])
    return bytes(out)


def page_density(w):
    """Darkness: GS E n (MPT-II manual), ESC 7 (Adafruit/ZJ), DC2 # (Chinese firmwares).
    A command the firmware ignores prints identical bars — that's the finding."""
    bar = gradient_image(w, 40).convert("1", dither=Image.FLOYDSTEINBERG)
    out = bytearray([ESC, 0x40])
    for n in (0, 5, 10, 15):
        out += bytes([GS, 0x45, n])
        out += text(f"GS E {n}")
        out += img_job(bar)
    out += bytes([ESC, 0x40])
    for heat in (40, 80, 120, 160, 200, 255):
        out += bytes([ESC, 0x37, 7, heat, 2])
        out += text(f"ESC 7 7 {heat} 2")
        out += img_job(bar)
    out += bytes([ESC, 0x40])
    for n in (0x00, 0x4F, 0x9F, 0xFF):
        out += bytes([DC2, 0x23, n])
        out += text(f"DC2 # 0x{n:02x}")
        out += img_job(bar)
    out += bytes([ESC, 0x40, ESC, 0x64, 2])
    return bytes(out)


def page_modes(w):
    """GS v 0 m=0..3 (normal/double width/double height/quad)."""
    im = Image.new("1", (w // 2, 40), 1)
    ImageDraw.Draw(im).ellipse([(0, 0), (w // 2 - 1, 39)], outline=0, width=3)
    out = bytearray([ESC, 0x40])
    for m in range(4):
        out += text(f"GS v 0 m={m}")
        out += img_job(im, mode=m)
    out += bytes([ESC, 0x64, 2])
    return bytes(out)


def page_escstar(w):
    """Fallback ESC * 33 (24-dot double density) for firmware without GS v 0."""
    im = gradient_image(w, 48).convert("1", dither=Image.FLOYDSTEINBERG)
    px = im.load()
    out = bytearray([ESC, 0x40]) + text("ESC * 33 (column mode)") + bytes([ESC, 0x33, 24])
    for y0 in range(0, im.height, 24):
        out += bytes([ESC, 0x2A, 33, w & 0xFF, w >> 8])
        for x in range(w):
            for k in range(3):
                b = 0
                for bit in range(8):
                    y = y0 + k * 8 + bit
                    if y < im.height and px[x, y] == 0:
                        b |= 0x80 >> bit
                out.append(b)
        out += b"\n"
    out += bytes([ESC, 0x32, ESC, 0x64, 2])
    return bytes(out)


def page_photo(w, path):
    bw = to_bitmap(path, w)
    return bytes([ESC, 0x40, ESC, 0x61, 1]) + raster_bytes(bw, 255) + bytes([ESC, 0x64, 3])


def page_cut(w):
    return bytes([ESC, 0x40]) + text("cut test: GS V B 48") + bytes([GS, 0x56, 0x42, 48])


def page_selftest(w):
    # Epson GS ( A not common; ZJ uses US vt eot (seen in vendor SDK Command.java)
    return bytes([0x1F, 0x11, 0x04])


def page_beep(w):
    return bytes([ESC, 0x42, 3, 2])


