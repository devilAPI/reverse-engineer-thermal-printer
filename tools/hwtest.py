# ----------------------------------------------------------------------- commands
def open_link(a):
    if a.ble:
        return BleLink(a.ble)
    if a.dev:
        return DevLink(a.dev)
    return UsbLink(a.usb)


def cmd_detect(a, log):
    import usb.core
    log.section("detect")
    lines = [describe(d) for d in usb.core.find(find_all=True)]
    log.block("\n".join(lines))
    nodes = subprocess.run("ls -l /dev/usb/lp* /dev/ttyACM* /dev/rfcomm* 2>/dev/null", shell=True,
                           capture_output=True, text=True).stdout
    log.block(nodes or "(no printer device nodes)")


def cmd_dump(a, log):
    link = UsbLink(a.usb)
    try:
        d = link.dev
        log.section(f"dump {d.idVendor:04x}:{d.idProduct:04x}")
        log.block(describe(d))
        out = subprocess.run(["lsusb", "-v", "-d", f"{d.idVendor:04x}:{d.idProduct:04x}"],
                             capture_output=True, text=True).stdout
        log.block(out)
        # USB printer class requests: GET_DEVICE_ID (IEEE 1284 id) and GET_PORT_STATUS
        if link.intf.bInterfaceClass == 0x07:
            try:
                raw = bytes(d.ctrl_transfer(0xA1, 0, 0, link.intf.bInterfaceNumber << 8, 1024))
                log.note(f"- GET_DEVICE_ID: `{raw[2:].decode('latin1', 'replace')}`")
            except Exception as e:  # noqa: BLE001
                log.note(f"- GET_DEVICE_ID failed: {e}")
            try:
                st = bytes(d.ctrl_transfer(0xA1, 1, 0, link.intf.bInterfaceNumber, 1))
                log.note(f"- GET_PORT_STATUS: 0x{st[0]:02x} = {bits(st)} "
                         "(bit5 paper empty, bit4 selected, bit3 not error)")
            except Exception as e:  # noqa: BLE001
                log.note(f"- GET_PORT_STATUS failed: {e}")
    finally:
        link.close()


def cmd_status(a, log):
    link = open_link(a)
    try:
        log.section(f"status via {link.name}")
        link.read(0.2)  # drain
        for name, q in STATUS_QUERIES:
            link.write(q)
            log.rx(name, link.read(0.6))
    finally:
        link.close()


def cmd_print(a, log):
    link = open_link(a)
    try:
        for name in a.pages:
            if name == "photo":
                if not a.image:
                    raise SystemExit("photo needs --image")
                job = page_photo(a.width, a.image)
            else:
                job = PAGES[name](a.width)
            log.section(f"print {name} via {link.name} (width {a.width}, chunk {a.chunk}, delay {a.delay})")
            log.tx(name, job)
            t = time.time()
            link.write(job, a.chunk, a.delay)
            el = time.time() - t
            log.note(f"- sent in {el:.2f} s ({len(job) / max(el, 1e-6) / 1024:.1f} KiB/s)")
            log.rx("after", link.read(0.3))
            if a.observe:
                obs = input(f"  What did '{name}' print? (enter = skip) > ").strip()
                if obs:
                    log.note(f"- **Observed:** {obs}")
    finally:
        link.close()


def cmd_raw(a, log):
    link = open_link(a)
    try:
        data = bytes.fromhex(a.hex)
        log.section(f"raw via {link.name}")
        log.tx("raw", data)
        link.write(data)
        log.rx("raw", link.read(a.wait))
    finally:
        link.close()


def cmd_ble_scan(a, log):
    from bleak import BleakScanner
    log.section("ble-scan")

    async def run():
        found = await BleakScanner.discover(timeout=8, return_adv=True)
        rows = []
        for addr, (dev, adv) in sorted(found.items(), key=lambda kv: -kv[1][1].rssi):
            rows.append(f"{addr} rssi={adv.rssi} name={adv.local_name or dev.name!r} "
                        f"services={adv.service_uuids} mfr={ {k: v.hex() for k, v in adv.manufacturer_data.items()} }")
        return rows
    log.block("\n".join(asyncio.run(run())) or "(nothing)")


def cmd_ble_dump(a, log):
    from bleak import BleakClient
    log.section(f"ble-dump {a.ble}")

    async def run():
        async with BleakClient(a.ble, timeout=20) as c:
            rows = [f"mtu={getattr(c, 'mtu_size', '?')}"]
            for s in c.services:
                rows.append(f"service {s.uuid} ({s.description})")
                for ch in s.characteristics:
                    val = ""
                    if "read" in ch.properties:
                        try:
                            v = await c.read_gatt_char(ch)
                            val = f" value={v.hex()} '{v.decode('latin1', 'replace')}'"
                        except Exception as e:  # noqa: BLE001
                            val = f" read failed: {e}"
                    rows.append(f"  char {ch.uuid} handle={ch.handle} {ch.properties}{val}")
            return rows
    log.block("\n".join(asyncio.run(run())))


